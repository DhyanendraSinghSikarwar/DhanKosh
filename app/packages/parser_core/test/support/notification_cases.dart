import 'package:parser_core/parser_core.dart';

/// One notification layout and what must come out of it. [type] null means it
/// must not become a transaction. [minor] is the amount in paise.
class NotificationCase {
  const NotificationCase(
    this.app,
    this.title,
    this.body, [
    this.type,
    this.minor,
    this.merchant,
    this.upi,
  ]);

  final String app;
  final String? title;
  final String? body;
  final TransactionType? type;
  final int? minor;
  final String? merchant;
  final String? upi;
}

/// A bank UPI SMS or a payment-app receipt email, and what must come out of it.
class ReceiptCase {
  const ReceiptCase(
    this.sender,
    this.body,
    this.source, [
    this.type,
    this.minor,
    this.merchant,
    this.last4,
    this.ref,
  ]);

  final String sender;
  final String body;
  final Source source;
  final TransactionType? type;
  final int? minor;
  final String? merchant;
  final String? last4;
  final String? ref;
}

